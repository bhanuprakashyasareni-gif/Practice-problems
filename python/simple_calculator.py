a = int(input("Enter the frist number : "))
b = int(input("Enter the second number : "))

operator = input("Enter the operator: ")

if operator == "+" :
    print(f"addition {a + b }")
elif operator == "-" :
    print(f"subtraction {a -b }")
elif operator == "*":
    print(f"multiplicaton {a * b}")

elif operator == "/" :
    print(f"division {a / b}")

